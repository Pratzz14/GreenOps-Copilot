/* Offline browser regression: run against the combined FastAPI/React server. */
const {chromium, expect}=require('@playwright/test');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const assert=require('node:assert/strict');
(async()=>{
 const url=process.env.EDA_URL||'http://127.0.0.1:8001';
 const artifacts=path.join(os.tmpdir(),'greenops-phase2-qa');fs.mkdirSync(artifacts,{recursive:true});
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1080}});
 const errors=[];let expectedUnavailable=false;let expectedFailures=0;page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(['error','warning'].includes(m.type())){if(expectedUnavailable&&m.text().includes('503'))expectedFailures++;else errors.push(m.text());}});
 await page.goto(url);await expect(page.getByRole('heading',{name:'Evidence before decisions.'})).toBeVisible();
 assert.match(await page.title(),/GreenOps/);
 const full=await (await page.request.get(url+'/api/v1/data-quality')).json();
 const total=full.sources.reduce((n,s)=>n+s.rows,0);
 await expect(page.getByLabel('Analysis summary')).toContainText(total.toLocaleString('en-US'));
 await expect(page.locator('.chart-grid svg')).toHaveCount(3);
 await page.screenshot({path:path.join(artifacts,'desktop-overview.png'),fullPage:false});
 await page.getByLabel('Unit / currency',{exact:true}).selectOption('GPU-hour');
 await page.getByLabel('Measurement',{exact:true}).selectOption('CostInBillingCurrency');
 await page.getByLabel('Unit / currency',{exact:true}).selectOption('EUR');
 await page.locator('#explorer').screenshot({path:path.join(artifacts,'measurement-distribution.png')});
 await page.getByRole('button',{name:'Baseline period',exact:true}).click();
 const base=await (await page.request.get(url+'/api/v1/data-quality?scope=baseline')).json();
 await expect(page.getByLabel('Analysis summary')).toContainText(base.sources.reduce((n,s)=>n+s.rows,0).toLocaleString('en-US'));
 await page.getByLabel('Evidence type',{exact:true}).selectOption('Monitoring and utilization');
 await expect(page.locator('#catalog tbody tr')).toHaveCount(2);
 await page.getByLabel('Evidence type',{exact:true}).selectOption('');
 await page.getByLabel('Find source',{exact:true}).fill('no-such-source');
 await expect(page.getByText('No sources match these filters.',{exact:false})).toBeVisible();
 await page.getByLabel('Find source',{exact:true}).fill('data_platform');
 await page.getByRole('button',{name:'data_platform_usage.csv',exact:false}).click();
 await expect(page.locator('#explorer h2')).toHaveText('data_platform_usage.csv');
 await page.getByRole('button',{name:'Coverage & joins',exact:true}).click();
 await expect(page.locator('#explorer .issue').filter({hasText:'dp-dev'})).toContainText('6 baseline absences');
 await page.locator('#explorer .issue').filter({hasText:'dp-dev'}).locator('summary').click();
 await expect(page.locator('#explorer')).toContainText('2026-06-23');
 await page.locator('#explorer').screenshot({path:path.join(artifacts,'coverage-and-joins.png')});
 await page.getByRole('button',{name:'Issues & evidence',exact:true}).click();
 await page.getByLabel('Filter findings',{exact:true}).selectOption('exact_duplicate_candidate');
 await expect(page.locator('#explorer .issue')).toHaveCount(2);
 await page.locator('#explorer .issue').first().locator('summary').first().click();
 await expect(page.locator('#explorer .issue').first()).toContainText('Identical raw fields');
 await page.getByRole('button',{name:'Canonical map',exact:true}).click();
 await expect(page.locator('#explorer tbody tr')).toHaveCount(16);
 await page.getByRole('button',{name:'Fields & distributions',exact:true}).click();
 await page.getByLabel('Measurement',{exact:true}).selectOption('active_use_h');
 await expect(page.locator('.distribution')).toContainText('Measurement distribution');
 await page.getByLabel('Find source',{exact:true}).fill('ai_subscriptions');
 await page.getByRole('button',{name:'ai_subscriptions.csv',exact:false}).click();
 await expect(page.locator('#explorer')).toContainText('contract_status');
 await expect(page.locator('#explorer .category-grid')).toContainText('Draft');
 await expect(page.locator('#explorer .category-grid')).toContainText('Final');
 await page.getByRole('button',{name:'Issues & evidence',exact:true}).click();
 await expect(page.locator('#explorer')).toContainText('Draft / Final coexistence groups');
 await page.screenshot({path:path.join(artifacts,'contract-evidence.png'),fullPage:true});
 // Keyboard interaction remains available for filters and view buttons.
 await page.getByRole('button',{name:'Full exports',exact:true}).focus();await page.keyboard.press('Enter');
 await expect(page.getByRole('button',{name:'Full exports',exact:true})).toHaveAttribute('aria-pressed','true');
 await page.setViewportSize({width:390,height:844});await page.goto(url);
 await expect(page.getByRole('heading',{name:'Evidence before decisions.'})).toBeVisible();
 await expect(page.locator('.chart-grid svg')).toHaveCount(3);
 await page.screenshot({path:path.join(artifacts,'mobile-debug.png'),fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile page overflows viewport');
 await page.screenshot({path:path.join(artifacts,'mobile-overview.png'),fullPage:false});
 assert.deepEqual(errors,[],'Unexpected browser errors/warnings');
 // Delay, unavailable report, then retry against the same real server.
 expectedUnavailable=true;
 await page.route('**/api/v1/data-quality?scope=full',async route=>{await new Promise(r=>setTimeout(r,350));await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:{message:'Profiling report snapshot mismatch. Regenerate and restart.'}})});});
 await page.reload();await expect(page.getByText('Loading the source analysis…')).toBeVisible();
 await expect(page.getByRole('alert')).toContainText('snapshot mismatch');
 await page.screenshot({path:path.join(artifacts,'unavailable-report.png'),fullPage:false});
 await page.unroute('**/api/v1/data-quality?scope=full');await page.getByRole('button',{name:'Try again',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Evidence before decisions.'})).toBeVisible();
 assert.deepEqual(errors,[],'Unexpected browser errors after retry');
 console.log(JSON.stringify({url,viewports:['1440x1080','390x844'],checks:'overview,charts,baseline,filters,empty,source,coverage,gaps,joins,issues,evidence,mapping,distribution,contracts,keyboard,loading,error,retry',artifacts,unexpectedBrowserErrors:errors,expectedUnavailableResponses:expectedFailures},null,2));
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
